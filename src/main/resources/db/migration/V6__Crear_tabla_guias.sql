-- =====================================================================
-- 5. Guías sugeridas para entrevistas
-- =====================================================================

CREATE TABLE guias (
                       id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       titulo         VARCHAR(150) NOT NULL,
                       empresa_id     BIGINT       NOT NULL,
                       cuenta_id      BIGINT       NOT NULL,
                       creado_en      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       actualizado_en TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       CONSTRAINT fk_guias_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
                       CONSTRAINT fk_guias_cuenta  FOREIGN KEY (cuenta_id)  REFERENCES cuentas (id)
);

CREATE TABLE guias_preguntas (
                                 guia_id        BIGINT       NOT NULL,
                                 pregunta       TEXT         NOT NULL,
                                 CONSTRAINT fk_guias_preguntas_guia FOREIGN KEY (guia_id)
                                     REFERENCES guias (id) ON DELETE CASCADE
);

CREATE INDEX idx_guias_empresa_id ON guias (empresa_id);
CREATE INDEX idx_guias_cuenta_id  ON guias (cuenta_id);
CREATE INDEX idx_guias_preguntas_guia_id ON guias_preguntas (guia_id);
