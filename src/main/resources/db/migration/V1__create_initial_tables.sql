-- ---------------------------------------------------------------------
-- 1. Tablas independientes
-- ---------------------------------------------------------------------
CREATE TABLE empresas (
                          id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre         VARCHAR(150) NOT NULL,
                          creado_en      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          actualizado_en TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE paquetes (
                          id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre         VARCHAR(50)   NOT NULL,
                          cantidad_salas INTEGER       NOT NULL,
                          precio         NUMERIC(12,2) NOT NULL,
                          es_activo      BOOLEAN       NOT NULL DEFAULT TRUE,
                          creado_en      TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          actualizado_en TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          CONSTRAINT uq_paquetes_nombre UNIQUE (nombre),
                          CONSTRAINT ck_paquetes_valores CHECK (cantidad_salas >= 1 AND precio >= 0)
);

-- ---------------------------------------------------------------------
-- 2. Tablas que dependen de empresas
-- ---------------------------------------------------------------------
CREATE TABLE cuentas (
                         id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         empresa_id        BIGINT       NULL,
                         nombre_completo   VARCHAR(100) NOT NULL,
                         correo            VARCHAR(254) NOT NULL,
                         google_sub        VARCHAR(255) NULL,
                         rol               VARCHAR(30)  NOT NULL ,
                         estado            VARCHAR(20)  NOT NULL DEFAULT 'ACTIVA',
                         ultimo_ingreso_en TIMESTAMPTZ  NULL,
                         version           INTEGER      NOT NULL DEFAULT 0,
                         creado_en         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         actualizado_en    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         CONSTRAINT fk_cuentas_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
                         CONSTRAINT uq_cuentas_correo UNIQUE (correo)

);

CREATE TABLE productos (
                           id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           empresa_id     BIGINT       NOT NULL,
                           nombre         VARCHAR(100) NOT NULL,
                           descripcion    VARCHAR(500) NULL,
                           categoria      VARCHAR(60)  NULL,
                           es_activo      BOOLEAN      NOT NULL DEFAULT TRUE,
                           version        INTEGER      NOT NULL DEFAULT 0,
                           creado_en      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           actualizado_en TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           CONSTRAINT fk_productos_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id)
);

-- Nombre único dentro de la empresa, sin distinguir mayúsculas (RF-04)
CREATE UNIQUE INDEX uq_productos_empresa_nombre
    ON productos (empresa_id, lower(nombre));

-- ---------------------------------------------------------------------
-- 3. Tablas que dependen de cuentas, paquetes o productos
-- ---------------------------------------------------------------------
CREATE TABLE compras (
                         id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         empresa_id         BIGINT        NOT NULL,
                         paquete_id         BIGINT        NOT NULL,
                         cuenta_id          BIGINT        NOT NULL,
                         monto              NUMERIC(12,2) NOT NULL,
                         salas_acreditadas  INTEGER       NOT NULL,
                         estado_pago        VARCHAR(20)   NOT NULL,
                         referencia_pago    VARCHAR(100)  NULL,
                         clave_idempotencia UUID          NOT NULL,
                         creado_en          TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         CONSTRAINT fk_compras_empresa FOREIGN KEY (empresa_id) REFERENCES empresas (id),
                         CONSTRAINT fk_compras_paquete FOREIGN KEY (paquete_id) REFERENCES paquetes (id),
                         CONSTRAINT fk_compras_cuenta  FOREIGN KEY (cuenta_id)  REFERENCES cuentas (id),
                         CONSTRAINT uq_compras_clave_idempotencia UNIQUE (clave_idempotencia)

);

CREATE TABLE cambios_rol (
                             id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             cuenta_id    BIGINT      NOT NULL,
                             autor_id     BIGINT      NOT NULL,
                             rol_anterior VARCHAR(30) NOT NULL,
                             rol_nuevo    VARCHAR(30) NOT NULL,
                             creado_en    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             CONSTRAINT fk_cambios_rol_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuentas (id),
                             CONSTRAINT fk_cambios_rol_autor  FOREIGN KEY (autor_id)  REFERENCES cuentas (id)
);

CREATE TABLE salas (
                       id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       producto_id         BIGINT      NOT NULL,
                       creado_por_id       BIGINT      NOT NULL,
                       token               VARCHAR(64) NOT NULL,
                       estado              VARCHAR(20) NOT NULL,
                       emitida_en          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       vence_en            TIMESTAMPTZ NOT NULL,
                       nombre_consumidor   VARCHAR(60) NULL,
                       acepto_grabacion_en TIMESTAMPTZ NULL,
                       CONSTRAINT fk_salas_producto   FOREIGN KEY (producto_id)   REFERENCES productos (id),
                       CONSTRAINT fk_salas_creado_por FOREIGN KEY (creado_por_id) REFERENCES cuentas (id),
                       CONSTRAINT uq_salas_token UNIQUE (token)

);

-- ---------------------------------------------------------------------
-- 4. Flujo de entrevistas, grabaciones, transcripción y análisis
-- ---------------------------------------------------------------------
CREATE TABLE entrevistas (
                             id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             sala_id           BIGINT      NOT NULL,
                             representante_id  BIGINT      NOT NULL,
                             estado            VARCHAR(20) NOT NULL,
                             inicio_en         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             fin_en            TIMESTAMPTZ NULL,
                             duracion_segundos INTEGER     NULL,
                             CONSTRAINT fk_entrevistas_sala          FOREIGN KEY (sala_id)          REFERENCES salas (id),
                             CONSTRAINT fk_entrevistas_representante FOREIGN KEY (representante_id) REFERENCES cuentas (id)

);

CREATE TABLE grabaciones (
                             id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             entrevista_id            BIGINT       NOT NULL,
                             ruta_canal_cliente       VARCHAR(255) NOT NULL,
                             ruta_canal_representante VARCHAR(255) NULL,
                             formato                  VARCHAR(20)  NOT NULL,
                             tamano_bytes             BIGINT       NOT NULL,
                             duracion_segundos        INTEGER      NOT NULL,
                             hash_sha256              CHAR(64)     NOT NULL,
                             tiene_audio_cliente      BOOLEAN      NOT NULL DEFAULT TRUE,
                             es_parcial               BOOLEAN      NOT NULL DEFAULT FALSE,
                             estado                   VARCHAR(20)  NOT NULL,
                             creado_en                TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             CONSTRAINT fk_grabaciones_entrevista FOREIGN KEY (entrevista_id) REFERENCES entrevistas (id),
                             CONSTRAINT uq_grabaciones_entrevista_id UNIQUE (entrevista_id),
                             CONSTRAINT ck_grabaciones_tamano CHECK (tamano_bytes > 0 AND tamano_bytes <= 209715200)
);

CREATE TABLE transcripciones (
                                 id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 grabacion_id        BIGINT       NOT NULL,
                                 texto               TEXT         NULL,
                                 idioma_detectado    VARCHAR(10)  NULL,
                                 probabilidad_idioma NUMERIC(4,3) NULL,
                                 estado              VARCHAR(20)  NOT NULL,
                                 intentos            SMALLINT     NOT NULL,
                                 mensaje_error       VARCHAR(500) NULL,
                                 creado_en           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 actualizado_en      TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 CONSTRAINT fk_transcripciones_grabacion FOREIGN KEY (grabacion_id) REFERENCES grabaciones (id),
                                 CONSTRAINT uq_transcripciones_grabacion_id UNIQUE (grabacion_id),
                                 CONSTRAINT ck_transcripciones_probabilidad CHECK (probabilidad_idioma IS NULL OR probabilidad_idioma BETWEEN 0 AND 1)
);

CREATE TABLE fragmentos_transcripcion (
                                          id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          transcripcion_id BIGINT       NOT NULL,
                                          segundo_inicio   NUMERIC(8,2) NOT NULL,
                                          segundo_fin      NUMERIC(8,2) NOT NULL,
                                          texto            TEXT         NOT NULL,
                                          CONSTRAINT fk_fragmentos_transcripcion FOREIGN KEY (transcripcion_id)
                                              REFERENCES transcripciones (id) ON DELETE CASCADE
);

CREATE TABLE analisis (
                          id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          transcripcion_id BIGINT        NOT NULL,
                          estado           VARCHAR(20)   NOT NULL DEFAULT 'PENDIENTE',
                          intencion        VARCHAR(20)   NULL,
                          sentimiento      VARCHAR(10)   NULL,
                          fragmento_apoyo  VARCHAR(1000) NULL,
                          tiene_menciones  BOOLEAN       NOT NULL DEFAULT FALSE,
                          proveedor_ia     VARCHAR(60)   NULL,
                          intentos         SMALLINT      NOT NULL DEFAULT 0,
                          mensaje_error    VARCHAR(500)  NULL,
                          creado_en        TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          actualizado_en   TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          CONSTRAINT fk_analisis_transcripcion FOREIGN KEY (transcripcion_id) REFERENCES transcripciones (id),
                          CONSTRAINT uq_analisis_transcripcion_id UNIQUE (transcripcion_id)

);

CREATE TABLE menciones_competencia (
                                       id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       analisis_id BIGINT       NOT NULL,
                                       competidor  VARCHAR(100) NOT NULL,
                                       frecuencia  SMALLINT     NOT NULL,
                                       contexto    VARCHAR(500) NULL,
                                       CONSTRAINT fk_menciones_analisis FOREIGN KEY (analisis_id)
                                           REFERENCES analisis (id) ON DELETE CASCADE

);